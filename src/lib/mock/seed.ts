const company = (
  id: string,
  name: string,
  slug: string,
  location: string,
  description: string,
  website: string,
  status: Company["status"],
  ownerEmail: string,
  submittedDaysAgo: number,
  verified = false,
  suspensionReason?: string,
): Company => ({
  id,
  name,
  slug,
  location,
  description,
  website,
  status,
  ownerEmail,
  logoText: name
    .split(" ")
    .slice(0, 2)
    .map((w) => w[0])
    .join(""),
  submittedAt: daysAgo(submittedDaysAgo),
  verified,
  suspensionReason,
});

